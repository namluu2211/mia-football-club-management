#!/usr/bin/env node
/**
 * Generates Firebase security rules from src/app/config/admin-users.json (single source of truth).
 *
 *   node scripts/generate-firebase-rules.js          -> writes database.rules.json and storage.rules
 *   node scripts/generate-firebase-rules.js --check  -> exits 1 if the committed files are out of date
 *
 * Policy: everyone can read (guest mode); only listed admin emails can write.
 * Anything not listed under "rules" is write-protected by default.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ADMINS_FILE = path.join(ROOT, 'src', 'app', 'config', 'admin-users.json');
const DB_RULES_FILE = path.join(ROOT, 'database.rules.json');
const STORAGE_RULES_FILE = path.join(ROOT, 'storage.rules');

/** Top-level Realtime Database nodes the app writes to. Keep in sync with the services. */
const WRITABLE_DB_NODES = [
  'history',
  'players',
  'playerAvatars',
  'playerMedia',
  'matchResults',
  'playerStats',
  'fundTransactions',
  'statistics'
];

const MAX_VIDEO_BYTES = 50 * 1024 * 1024;

function loadAdminEmails() {
  const users = JSON.parse(fs.readFileSync(ADMINS_FILE, 'utf8'));
  const emails = users.map(u => String(u.email).trim().toLowerCase());
  const invalid = emails.filter(e => !/^[^\s@'"\\]+@[^\s@'"\\]+\.[^\s@'"\\]+$/.test(e));
  if (!emails.length || invalid.length) {
    throw new Error(`admin-users.json must contain valid emails. Invalid: ${JSON.stringify(invalid)}`);
  }
  return emails;
}

function buildDatabaseRules(emails) {
  const isAdmin = 'auth != null && (' + emails.map(e => `auth.token.email.toLowerCase() == '${e}'`).join(' || ') + ')';
  const rules = { '.read': true };
  for (const node of WRITABLE_DB_NODES) rules[node] = { '.write': isAdmin };
  return { rules };
}

function buildStorageRules(emails) {
  const list = emails.map(e => `'${e}'`).join(', ');
  return `// Generated by scripts/generate-firebase-rules.js. Do not edit by hand.
rules_version = '2';
service firebase.storage {
  match /b/{bucket}/o {
    function isAdmin() {
      return request.auth != null
        && request.auth.token.email != null
        && request.auth.token.email.lower() in [${list}];
    }

    // Player media: public read, admin-only write, videos capped at ${MAX_VIDEO_BYTES / (1024 * 1024)} MB.
    match /players/{playerId}/videos/{fileName} {
      allow read: if true;
      allow write: if isAdmin()
        && request.resource.size < ${MAX_VIDEO_BYTES}
        && request.resource.contentType.matches('video/.*');
      allow delete: if isAdmin();
    }

    // Everything else is closed.
    match /{allPaths=**} {
      allow read, write: if false;
    }
  }
}
`;
}

function render() {
  const emails = loadAdminEmails();
  return {
    [DB_RULES_FILE]: JSON.stringify(buildDatabaseRules(emails), null, 2) + '\n',
    [STORAGE_RULES_FILE]: buildStorageRules(emails)
  };
}

if (require.main === module) {
  const outputs = render();
  if (process.argv.includes('--check')) {
    const stale = Object.entries(outputs).filter(([file, text]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== text);
    if (stale.length) {
      console.error('Out of date (run: npm run firebase:rules):\n' + stale.map(([f]) => '  ' + path.relative(ROOT, f)).join('\n'));
      process.exit(1);
    }
    console.log('Firebase rules are up to date.');
  } else {
    for (const [file, text] of Object.entries(outputs)) {
      fs.writeFileSync(file, text, 'utf8');
      console.log('Wrote ' + path.relative(ROOT, file));
    }
  }
}

module.exports = { WRITABLE_DB_NODES, buildDatabaseRules, buildStorageRules, loadAdminEmails };
